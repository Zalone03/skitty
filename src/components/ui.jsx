export function useToast() {
  const [toast, setToast] = useState(null);
  const timer = useRef(null);
  const show = useCallback((text, tone = "ok") => {
    clearTimeout(timer.current);
    setToast({ text, tone, id: Date.now() });
    timer.current = setTimeout(() => setToast(null), 2600);
  }, []);
  const node = toast ? (
    <div className={`toast ${toast.tone}`} key={toast.id} role="status">
      {toast.text}
    </div>
  ) : null;
  return { show, node };
}

export function ColorDots({ colors, value, onChange }) {
  return (
    <div className="color-dots">
      {colors.map((c) => (
        <button key={c} className={`color-dot ${c === value ? "on" : ""}`} style={{ background: c }} onClick={() => onChange(c)} aria-label={`Cor ${c}`} />
      ))}
    </div>
  );
}

export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement("textarea");
    ta.value = text;
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    ta.remove();
    return ok;
  }
}
